SET TIME ZONE 'UTC';

CREATE TABLE IF NOT EXISTS public.articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    content TEXT NOT NULL,
    published_at TIMESTAMPTZ,
    author_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    deleted_at TIMESTAMPTZ,
    -- Rejects empty titles and impossible timestamp ordering.
    CONSTRAINT articles_title_not_blank CHECK (btrim(title) <> ''),
    CONSTRAINT articles_updated_after_created CHECK (updated_at >= created_at),
    CONSTRAINT articles_deleted_after_created CHECK (
        deleted_at IS NULL OR deleted_at >= created_at
    )
);

-- Maintains updated_at while allowing controlled timestamp test cases.
CREATE OR REPLACE FUNCTION public.set_article_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    -- Test helpers can preserve or explicitly set updated_at to exercise
    -- defensive extraction behavior and exact interval boundaries.
    IF current_setting('app.preserve_updated_at', true) = 'on' THEN
        RETURN NEW;
    END IF;

    IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
        NEW.updated_at = clock_timestamp();
    END IF;

    RETURN NEW;
END;
$$;

-- Recreates the trigger safely when the initialization script is rerun.
DROP TRIGGER IF EXISTS articles_set_updated_at ON public.articles;
CREATE TRIGGER articles_set_updated_at
BEFORE UPDATE ON public.articles
FOR EACH ROW
EXECUTE FUNCTION public.set_article_updated_at();

-- Supports stable incremental extraction ordered by (updated_at, id).
CREATE INDEX IF NOT EXISTS articles_updated_id_idx
    ON public.articles (updated_at, id);

-- Supports stable historical backfill ordered by (created_at, id).
CREATE INDEX IF NOT EXISTS articles_created_id_idx
    ON public.articles (created_at, id);

-- Speeds up soft-delete scans without indexing active rows.
CREATE INDEX IF NOT EXISTS articles_deleted_id_idx
    ON public.articles (deleted_at, id)
    WHERE deleted_at IS NOT NULL;

-- Creates the local read-only extraction account once.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'source_reader') THEN
        -- Local simulator credential only; never use in shared environments.
        CREATE ROLE source_reader LOGIN PASSWORD 'source_reader';
    END IF;

    -- Allows the reader role to connect to whichever database is initialized.
    EXECUTE format(
        'GRANT CONNECT ON DATABASE %I TO source_reader',
        current_database()
    );
END;
$$;

-- Grants only the access required to connect and read source data.
GRANT USAGE ON SCHEMA public TO source_reader;
GRANT SELECT ON public.articles TO source_reader;

-- Gives the reader SELECT access to future tables created in this schema.
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT ON TABLES TO source_reader;
